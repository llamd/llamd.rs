//! Compile the GLSL compute shaders to SPIR-V and the Vulkan host to a static
//! library, if the toolchain is present.
//!
//! WHY DETECT RATHER THAN REQUIRE, as in llamd-rocm: `cargo build --workspace`
//! must work on a machine with no Vulkan and no glslc — CI, a laptop, a
//! reviewer's box. An absent toolchain is not an error; the crate compiles to a
//! stub that reports unavailability and the tests skip loudly.

use std::path::{Path, PathBuf};
use std::process::Command;

const SHADERS: &[(&str, &str)] = &[("q6k_matvec", "shaders/q6k_matvec.comp")];

fn main() {
    println!("cargo::rerun-if-changed=shaders");
    println!("cargo::rerun-if-changed=vk");
    println!("cargo::rustc-check-cfg=cfg(vulkan)");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());

    let glslc = which("glslc");
    let Some(glslc) = glslc else {
        println!("cargo::warning=glslc not found; llamd-vulkan builds as a stub");
        return;
    };
    if !Path::new("/usr/include/vulkan/vulkan.h").exists() && which("pkg-config").is_none() {
        println!("cargo::warning=vulkan headers not found; llamd-vulkan builds as a stub");
        return;
    }

    // Each shader becomes a `static const uint32_t SPV_<NAME>[]` in one header,
    // so the SPIR-V travels inside the library and there is no file to locate
    // at runtime.
    let mut header = String::from(
        "// Generated by build.rs from shaders/*.comp. Do not edit.\n\
         #pragma once\n#include <stdint.h>\n\n",
    );
    for (name, src) in SHADERS {
        let spv = out_dir.join(format!("{name}.spv.h"));
        let status = Command::new(&glslc)
            .args([
                "-fshader-stage=compute",
                "--target-env=vulkan1.3",
                "-O",
                "-mfmt=c",
            ])
            .arg(src)
            .arg("-o")
            .arg(&spv)
            .status();
        match status {
            Ok(s) if s.success() => {}
            _ => {
                println!("cargo::warning=glslc failed on {src}; llamd-vulkan builds as a stub");
                return;
            }
        }
        let body = std::fs::read_to_string(&spv).expect("read spv");
        header.push_str(&format!(
            "static const uint32_t SPV_{}[] = {};\n\n",
            name.to_uppercase(),
            body.trim().trim_end_matches(';')
        ));
    }
    let hdr = out_dir.join("shaders_spv.h");
    std::fs::write(&hdr, header).expect("write header");

    let obj = out_dir.join("llamd_vk.o");
    let lib = out_dir.join("libllamd_vk.a");
    let status = Command::new("c++")
        .args(["-O3", "-c", "-fPIC", "-std=c++17"])
        .arg(format!("-I{}", out_dir.display()))
        .arg("vk/llamd_vk.cpp")
        .arg("-o")
        .arg(&obj)
        .status();
    match status {
        Ok(s) if s.success() => {}
        _ => {
            println!("cargo::warning=c++ failed on vk/llamd_vk.cpp; llamd-vulkan builds as a stub");
            return;
        }
    }
    let _ = std::fs::remove_file(&lib);
    let _ = Command::new("ar").arg("crs").arg(&lib).arg(&obj).status();

    println!("cargo::rustc-link-search=native={}", out_dir.display());
    println!("cargo::rustc-link-lib=static=llamd_vk");
    println!("cargo::rustc-link-lib=dylib=vulkan");
    println!("cargo::rustc-link-lib=dylib=stdc++");
    println!("cargo::rustc-cfg=vulkan");
    println!("cargo::warning=llamd-vulkan: built with Vulkan compute support");
}

fn which(bin: &str) -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|p| p.join(bin))
        .find(|p| p.is_file())
}
